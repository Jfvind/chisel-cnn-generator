package shell

import java.io.{File, PrintWriter}
import circt.stage.ChiselStage      // For Verilog

// =============================================================================
// ShellGen.scala — generates everything the FPGA flow needs into one directory:
//
//   AccelShell.sv      the Chisel design (SystemVerilog)
//   accel_top.v        plain-Verilog wrapper: Vivado block-design module references do not
//                      accept a SystemVerilog top file, and the wrapper carries the
//                      X_INTERFACE attributes that tie s_axi/s_axis/m_axis to aclk/aresetn.
//   shell_params.tcl   values build.tcl needs (stream width, clock, ...)
//   hw_manifest.json   values the PYNQ driver needs (register map, sizes, id, hash)
//
// ShellGen : App entry point, parses --out --core --nIn --nOut --streamW --addrW --fclkMhz
// Wrapper  : port list + Verilog wrapper text
// Manifest : shell_params.tcl and hw_manifest.json text
//
// Usage (from generator/):
//   sbt "runMain shell.ShellGen --out ../hw/vivado/rtl --core stub --streamW 32"
// =============================================================================

object ShellGen extends App {           // App provides args from CLI
    // "--name value" lookup else default
    private def argOr(name: String, default: String): String = {
        val i = args.indexOf(s"--$name")
        if (i >= 0 && i + 1 < args.length) args(i+1) else default
    }

    val requested = AccelConfig(
        core    = argOr("core", "stub"),
        nIn     = argOr("nIn", "784").toInt,
        nOut    = argOr("nOut", "10").toInt,
        streamW = argOr("streamW", "32").toInt,
        addrW   = argOr("addrW", "12").toInt,
        fclkMhz = argOr("fclkMhz", "100").toInt,
        weightBiasDir = argOr("weightBiasDir", "../python")
    )
    val cfg = AccelConfig.resolve(requested)       // core-specific rules (stub: nOut = nIn)
    if (cfg != requested) println(s"[ShellGen] adjusted for core '${cfg.core}': $requested -> $cfg")
    val outDir = new File(argOr("out", "../hw/vivado/rtl"))
    outDir.mkdirs()

    ChiselStage.emitSystemVerilogFile(              // creates <outDir>/AccelShell.sv
        new AccelShell(cfg),
        Array("--target-dir", outDir.getPath),
        Array(
            "-disable-all-randomization",
            "-strip-debug-info",
            "--lowering-options=disallowLocalVariables,disallowPackedArrays"
        )
    )
    // firtool guards memory init ($readmemh of the mlp weight banks) with this macro; without it BRAMs synthesize empty
    val sv = new File(outDir, "AccelShell.sv")
    write(sv, "`define ENABLE_INITIAL_MEM_\n" + java.nio.file.Files.readString(sv.toPath))

    write(new File(outDir, "accel_top.v"), Wrapper.verilog(cfg))
    write(new File(outDir, "shell_params.tcl"), Manifest.tcl(cfg))
    write(new File(outDir, "hw_manifest.json"), Manifest.json(cfg))
    println(s"[ShellGen] $cfg -> ${outDir.getAbsolutePath}")

    private def write(f: File, s: String): Unit = {
        val pw = new PrintWriter(f)
        try pw.write(s) finally pw.close()
    }
}

object Wrapper {
    // (name, isInput, width) matching AccelShell
    def ports(cfg: AccelConfig): Seq[(String, Boolean, Int)] = {
        val a = cfg.addrW 
        val s = cfg.streamW
        Seq(
            ("s_axi_awaddr", true, a), ("s_axi_awprot", true, 3), ("s_axi_awvalid", true, 1), ("s_axi_awready", false, 1),
            ("s_axi_wdata", true, 32), ("s_axi_wstrb", true, 4), ("s_axi_wvalid", true, 1), ("s_axi_wready", false, 1),
            ("s_axi_bresp", false, 2), ("s_axi_bvalid", false, 1), ("s_axi_bready", true, 1),
            ("s_axi_araddr", true, a), ("s_axi_arprot", true, 3), ("s_axi_arvalid", true, 1), ("s_axi_arready", false, 1),
            ("s_axi_rdata", false, 32), ("s_axi_rresp", false, 2), ("s_axi_rvalid", false, 1), ("s_axi_rready", true, 1),
            ("s_axis_tdata", true, s), ("s_axis_tvalid", true, 1), ("s_axis_tready", false, 1), ("s_axis_tlast", true, 1),
            ("m_axis_tdata", false, s), ("m_axis_tvalid", false, 1), ("m_axis_tready", true, 1), ("m_axis_tlast", false, 1)
        )
    }

    def verilog(cfg: AccelConfig): String = {
        def decl(p: (String, Boolean, Int)): String = {         // port declaration
            val (n, in, w) = p
            val dir = if (in) "input wire" else "output wire"
            val rng = if (w > 1) s"[${w - 1}:0] " else ""
            s"  $dir $rng$n"
        }
        val ps = ports(cfg)
        // stripMargin removes everything before and including | on a line
        // INTERFACES tells that the clock applies to the axi interfaces
        // and that reset is active low.
        s"""// Generated by shell.ShellGen -- do not touch.
            |`timescale 1ns / 1ps
            |module accel_top (
            |  (* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 aclk CLK" *)
            |  (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF s_axi:s_axis:m_axis, ASSOCIATED_RESET aresetn" *)
            |  input  wire aclk,
            |  (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 aresetn RST" *)
            |  (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW" *)
            |  input  wire aresetn,
            |${ps.map(decl).mkString(",\n")}
            |);
            |  AccelShell inner (
            |    .aclk(aclk),
            |    .aresetn(aresetn),
            |${ps.map { case (n, _, _) => s"    .$n($n)"}.mkString(",\n")}
            |  );
            |endmodule
            |""".stripMargin
    }
}

object Manifest {
    // Sourced by build.tcl
    def tcl(cfg: AccelConfig): String =
        s"""# Generated by shell.ShellGen
            |set CORE     "${cfg.core}"
            |set STREAM_W ${cfg.streamW}
            |set ADDR_W   ${cfg.addrW}
            |set FCLK_MHZ ${cfg.fclkMhz}
            |""".stripMargin
    
    // read by accel.py on the board
    def json(cfg: AccelConfig): String = {
        val regs = RegMap.offsets.map { case (n, o) => s""" "$n": $o""" }.mkString(",\n")
        s"""{
            |  "core": "${cfg.core}",
            |  "id": ${cfg.id},
            |  "cfg_hash": ${cfg.cfgHash},
            |  "n_in": ${cfg.nIn},
            |  "n_out": ${cfg.nOut},
            |  "stream_w": ${cfg.streamW},
            |  "addr_w": ${cfg.addrW},
            |  "fclk_mhz": ${cfg.fclkMhz},
            |  "num_args": ${RegMap.NUM_ARGS},
            |  "regs": {
            |$regs
            |  }
            |}
            |""".stripMargin
    }
}